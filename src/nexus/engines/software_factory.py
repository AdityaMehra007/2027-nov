"""
ATLAS NEXUS: Mission 05 - Universal Software Factory & Product Foundry
Autonomous project scaffolding, AST code validation, and test harness synthesis.
"""

import ast
from dataclasses import dataclass
from typing import Dict, Optional


@dataclass
class ScaffoldedProject:
    name: str
    project_type: str
    files: Dict[str, str]


@dataclass
class CodeValidationResult:
    is_valid: bool
    ast_node_count: int
    error_message: Optional[str] = None


class SoftwareFactory:
    def scaffold_project(self, name: str, project_type: str = "saas_service") -> ScaffoldedProject:
        files: Dict[str, str] = {
            "main.py": (
                f'"""{name} - Generated by ATLAS NEXUS Software Factory"""\n'
                f'from fastapi import FastAPI\n\n'
                f'app = FastAPI(title="{name}")\n\n'
                f'@app.get("/healthz")\n'
                f'def healthz():\n'
                f'    return {{"status": "OK", "app": "{name}"}}\n'
            ),
            "test_main.py": (
                f'"""Unit tests for {name}"""\n'
                f'from fastapi.testclient import TestClient\n'
                f'from main import app\n\n'
                f'client = TestClient(app)\n\n'
                f'def test_health():\n'
                f'    res = client.get("/healthz")\n'
                f'    assert res.status_code == 200\n'
                f'    assert res.json()["status"] == "OK"\n'
            ),
            "requirements.txt": "fastapi>=0.115.0\nuvicorn>=0.30.0\npytest>=8.0.0\n",
            "README.md": (
                f"# {name}\n\n"
                f"Autonomous microservice generated by **ATLAS NEXUS Software Factory**.\n\n"
                f"## Run Tests\n```bash\npytest test_main.py\n```\n"
            ),
        }
        return ScaffoldedProject(name=name, project_type=project_type, files=files)

    def validate_code(self, code_str: str) -> CodeValidationResult:
        try:
            tree = ast.parse(code_str)
            node_count = sum(1 for _ in ast.walk(tree))
            return CodeValidationResult(is_valid=True, ast_node_count=node_count)
        except SyntaxError as e:
            return CodeValidationResult(
                is_valid=False,
                ast_node_count=0,
                error_message=f"SyntaxError: {e.msg} on line {e.lineno}",
            )
        except Exception as e:
            return CodeValidationResult(
                is_valid=False,
                ast_node_count=0,
                error_message=str(e),
            )
